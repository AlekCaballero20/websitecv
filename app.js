const DEFAULT_LANGUAGE = "es";
let currentLanguage = getStoredLanguage();

document.addEventListener("DOMContentLoaded", () => {
  setCurrentYear();
  setupLanguageSwitcher();
  applyLanguage(currentLanguage, { persist: false });
  setupMobileMenu();
  setupRevealAnimation();
  setupActiveSection();
});

function getStoredLanguage() {
  const stored = localStorage.getItem("siteLanguage");
  return translations[stored] ? stored : DEFAULT_LANGUAGE;
}

function t(key, language = currentLanguage) {
  return translations[language]?.[key] || translations[DEFAULT_LANGUAGE]?.[key] || key;
}

function applyLanguage(language, options = { persist: true }) {
  const nextLanguage = translations[language] ? language : DEFAULT_LANGUAGE;
  currentLanguage = nextLanguage;

  document.documentElement.lang = nextLanguage;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (!key) return;
    element.textContent = t(key, nextLanguage);
  });

  document.querySelectorAll("[data-i18n-attr]").forEach((element) => {
    const pairs = element.dataset.i18nAttr.split(";");
    pairs.forEach((pair) => {
      const [attribute, key] = pair.split(":").map((value) => value?.trim());
      if (!attribute || !key) return;
      element.setAttribute(attribute, t(key, nextLanguage));
    });
  });

  document.querySelectorAll(".language-switcher__button").forEach((button) => {
    const isActive = button.dataset.lang === nextLanguage;
    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  const menuToggle = document.querySelector(".nav__toggle");
  const menu = document.getElementById("nav-menu");
  if (menuToggle && menu) {
    const isOpen = menu.classList.contains("open");
    menuToggle.setAttribute("aria-label", t(isOpen ? "closeMenu" : "openMenu", nextLanguage));
  }

  if (options.persist) {
    localStorage.setItem("siteLanguage", nextLanguage);
  }
}

function setupLanguageSwitcher() {
  const buttons = document.querySelectorAll(".language-switcher__button");
  if (!buttons.length) return;

  buttons.forEach((button) => {
    button.addEventListener("click", () => {
      applyLanguage(button.dataset.lang);
    });
  });
}

function setCurrentYear() {
  const year = document.getElementById("year");
  if (year) year.textContent = new Date().getFullYear();
}

function setupMobileMenu() {
  const toggle = document.querySelector(".nav__toggle");
  const menu = document.getElementById("nav-menu");
  const links = document.querySelectorAll(".nav__menu a");

  if (!toggle || !menu) return;

  const setOpen = (open) => {
    menu.classList.toggle("open", open);
    toggle.setAttribute("aria-expanded", String(open));
    toggle.setAttribute("aria-label", t(open ? "closeMenu" : "openMenu"));
    document.body.classList.toggle("menu-open", open);
  };

  toggle.addEventListener("click", () => {
    setOpen(!menu.classList.contains("open"));
  });

  links.forEach((link) => {
    link.addEventListener("click", () => setOpen(false));
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") setOpen(false);
  });

  window.addEventListener("resize", () => {
    if (window.innerWidth > 760) setOpen(false);
  });
}

function setupRevealAnimation() {
  const elements = document.querySelectorAll(".reveal");
  if (!elements.length) return;

  if (!window.matchMedia("(prefers-reduced-motion: no-preference)").matches || !("IntersectionObserver" in window)) {
    elements.forEach((element) => element.classList.add("visible"));
    return;
  }

  const observer = new IntersectionObserver((entries, currentObserver) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add("visible");
      currentObserver.unobserve(entry.target);
    });
  }, { threshold: 0.12, rootMargin: "0px 0px -40px 0px" });

  elements.forEach((element) => observer.observe(element));
}

function setupActiveSection() {
  const sections = document.querySelectorAll("main section[id]");
  const links = document.querySelectorAll(".nav__menu a[href^='#']");

  if (!sections.length || !links.length || !("IntersectionObserver" in window)) return;

  const linkById = new Map();
  links.forEach((link) => {
    const id = link.getAttribute("href")?.replace("#", "");
    if (id) linkById.set(id, link);
  });

  const observer = new IntersectionObserver((entries) => {
    const visible = entries
      .filter((entry) => entry.isIntersecting)
      .sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];

    if (!visible) return;

    links.forEach((link) => link.classList.remove("active"));
    const activeLink = linkById.get(visible.target.id);
    if (activeLink) activeLink.classList.add("active");
  }, { threshold: [0.2, 0.35, 0.55], rootMargin: "-90px 0px -50% 0px" });

  sections.forEach((section) => observer.observe(section));
}
